int main() {
    const std::vector<std::pair<const char*, void(*)()>> tests{
        {"dataset_generator", TestDatasetGenerator},
        {"offset_generation", TestOffsetGeneration},
        {"validation_and_plan", TestValidationAndPlan},
        {"statistics_and_deadlines", TestStatisticsAndDeadlines},
        {"finalization_and_json", TestFinalizationAndJson},
        {"provider_injection", TestProviderInjection},
        {"migration_and_persistence", TestMigrationAndPersistence},
    };
    std::size_t passed = 0;
    for (const auto& [name, test] : tests) {
        try { test(); ++passed; std::cout << "PASS " << name << '\n'; }
        catch (const std::exception& error) {
            std::cerr << "FAIL " << name << ": " << error.what() << '\n';
        }
    }
    std::cout << passed << '/' << tests.size() << " storage tests passed\n";
    return passed == tests.size() ? 0 : 1;
}
